def safety_reply(lang: str, kind: str, alerted: bool) -> str | None:
    """The fixed emergency / distress line in `lang`, or None for mr / hi / en (handled in turn.py)."""
    row = SAFETY.get(lang)
    if row is None:
        return None
    if kind == "emergency":
        return row[0] if alerted else f"{row[1]} {row[4]}"
    return row[2] if alerted else f"{row[3]} {row[4]}"


